// ProximityChat! 1.0.RELEASE output format (§15.2, §15.3). Found during M0 by inspecting the plugin:
// it cancels AsyncPlayerChatEvent and re-sends each line with Player.sendMessage(String) — a *system*
// message, so mineflayer's `chat` event never fires; we parse `messagestr`. Fading only recolors the text.
// We write these exact formats into the plugin's config.yml, so the parser and the server agree by design.

import { stripColorCodes } from './text';
import type { Volume } from './schemas/common';

export const PCHAT_FORMATS = {
  default: '&7{player} &8» &f{message}',
  shout: '&c[Shout] &7{player} &8» &f{message}',
  whisper: '&e(Whisper) &7{player} &8» &f{message}',
  spy: '&8[Spy] &7{player} &8» &f{message}',
} as const;

export const PCHAT_PREFIXES = { shout: '!', whisper: '#' } as const;

export const PCHAT_NO_ONE_HEARD = '&8* No one heard you... *';

export interface ProximityChatSettings {
  normalRange: number;
  whisperRange: number;
  shoutRange: number;
  /** 0..1; plugin wants a percentage. */
  fadeStart: number;
  cooldownSec: number;
}

/** Renders the plugin's config.yml. Messages keep the plugin's defaults. */
export function renderProximityChatConfig(s: ProximityChatSettings): string {
  const q = (v: string): string => JSON.stringify(v);
  return [
    '# Generated by agora (scripts/server-mode.ts). Edit config/world.yaml `chat:` instead.',
    'ranges:',
    `  default: ${s.normalRange}`,
    `  shout: ${s.shoutRange}`,
    `  whisper: ${s.whisperRange}`,
    'prefixes:',
    `  shout: ${q(PCHAT_PREFIXES.shout)}`,
    `  whisper: ${q(PCHAT_PREFIXES.whisper)}`,
    'formats:',
    `  default: ${q(PCHAT_FORMATS.default)}`,
    `  shout: ${q(PCHAT_FORMATS.shout)}`,
    `  whisper: ${q(PCHAT_FORMATS.whisper)}`,
    `  spy: ${q(PCHAT_FORMATS.spy)}`,
    'features:',
    '  fade:',
    '    enabled: true',
    `    start-percentage: ${Math.round(s.fadeStart * 100)}`,
    '  sound:',
    '    enabled: true',
    '    sounds:',
    '      default: "ENTITY_EXPERIENCE_ORB_PICKUP"',
    '      shout: "ENTITY_PLAYER_ATTACK_STRONG"',
    '      whisper: "BLOCK_NOTE_BLOCK_CHIME"',
    '  cooldown:',
    `    enabled: ${s.cooldownSec > 0 ? 'true' : 'false'}`,
    `    time: ${Math.max(1, Math.round(s.cooldownSec))}`,
    'messages:',
    `  no-one-heard: ${q(PCHAT_NO_ONE_HEARD)}`,
    '',
  ].join('\n');
}

export type ParsedChatLine =
  | { kind: 'speech'; speaker: string; text: string; volume: Volume }
  | { kind: 'spy'; speaker: string; text: string }
  | { kind: 'noOneHeard' }
  | { kind: 'other'; text: string };

function plainTemplate(format: string): string {
  return stripColorCodes(format.replace(/&([0-9a-fk-or])/gi, '§$1'));
}

function templateToRegex(format: string): RegExp {
  const plain = plainTemplate(format);
  const escaped = plain.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = escaped.replace('\\{player\\}', '([A-Za-z0-9_]{1,16})').replace('\\{message\\}', '(.*)');
  return new RegExp(`^${pattern}$`, 's');
}

const SPY_RE = templateToRegex(PCHAT_FORMATS.spy);
const SHOUT_RE = templateToRegex(PCHAT_FORMATS.shout);
const WHISPER_RE = templateToRegex(PCHAT_FORMATS.whisper);
const DEFAULT_RE = templateToRegex(PCHAT_FORMATS.default);
const NO_ONE_HEARD = plainTemplate(PCHAT_NO_ONE_HEARD);

/** Parses one system chat line (`messagestr`). Color codes are stripped first. */
export function parseProximityLine(raw: string): ParsedChatLine {
  const line = stripColorCodes(raw).trim();
  if (line === NO_ONE_HEARD) return { kind: 'noOneHeard' };
  let m = SPY_RE.exec(line);
  if (m) return { kind: 'spy', speaker: m[1] ?? '', text: (m[2] ?? '').trim() };
  m = SHOUT_RE.exec(line);
  if (m) return { kind: 'speech', speaker: m[1] ?? '', text: (m[2] ?? '').trim(), volume: 'shout' };
  m = WHISPER_RE.exec(line);
  if (m) return { kind: 'speech', speaker: m[1] ?? '', text: (m[2] ?? '').trim(), volume: 'whisper' };
  m = DEFAULT_RE.exec(line);
  if (m) return { kind: 'speech', speaker: m[1] ?? '', text: (m[2] ?? '').trim(), volume: 'normal' };
  return { kind: 'other', text: line };
}

/** Outgoing text with the plugin prefix for the chosen volume. */
export function withVolumePrefix(text: string, volume: Volume): string {
  if (volume === 'shout') return `${PCHAT_PREFIXES.shout}${text}`;
  if (volume === 'whisper') return `${PCHAT_PREFIXES.whisper}${text}`;
  // A normal line must not accidentally start with a prefix character.
  return text.replace(/^[!#\s]+/, '');
}
